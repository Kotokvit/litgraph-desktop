/// Перевіряє, чи є слово українською назвою дня тижня.
pub fn is_uk_weekday(word: &str) -> bool {
    let lc = word.trim().to_lowercase();
    if lc.is_empty() {
        return false;
    }
    UK_WEEKDAYS.iter().any(|w| *w == lc)
}

/// Перевіряє, чи є слово українською назвою місяця.
