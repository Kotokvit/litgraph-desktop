/// Canonical hypothesis kinds per `POLER_UA_LP_MASTER_ROADMAP_V8.md` §Layer G.
///
/// Wire format: serde camelCase, so `Flashback` → `"flashback"`,
/// `DreamSequence` → `"dreamSequence"`, etc.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, Hash)]
#[serde(rename_all = "camelCase")]
pub enum HypothesisKind {
    /// Character's appearance after death is explained as a flashback
    /// (спогад про померлого).
    Flashback,
    /// Character's appearance after death is explained as a dream or
    /// hallucination (сон або галюцинація).
    DreamSequence,
    /// Character was not actually dead — medical/magical resurrection
    /// (сюжетне воскресіння).
    UnrecordedResurrection,
    /// The "dead" character is an impostor or twin
    /// (самозванець / подвійник).
    DisguisedIdentity,
}

impl HypothesisKind {
    /// Human-readable label for UI display.
    pub fn label(&self) -> &'static str {
        match self {
            Self::Flashback => "Flashback (спогад)",
            Self::DreamSequence => "Dream Sequence (сон)",
            Self::UnrecordedResurrection => "Unrecorded Resurrection (воскресіння)",
            Self::DisguisedIdentity => "Disguised Identity (самозванець)",
        }
    }

    /// All 4 canonical kinds, in canonical order.
    pub fn all() -> &'static [HypothesisKind] {
        &[
            Self::Flashback,
            Self::DreamSequence,
            Self::UnrecordedResurrection,
            Self::DisguisedIdentity,
        ]
    }
}

/// A single LLM-generated hypothesis for resolving a paradox.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Hypothesis {
    /// UUID-style identifier (generated by `make_hypothesis_id`).
    pub id: String,
    /// References [`Paradox::id`] — the paradox this hypothesis resolves.
    pub paradox_id: String,
    /// Canonical kind (one of 4).
    pub kind: HypothesisKind,
    /// 1-2 sentence summary of the hypothesis.
    pub summary: String,
    /// Full proposed chapter text (None until `generate_resolution_text`
    /// is called).
    pub proposed_text: Option<String>,
    /// LLM self-reported confidence in [0.0, 1.0].
    pub confidence: f64,
    /// Why this hypothesis fits the paradox (LLM-generated rationale).
    pub rationale: String,
}

/// Result of validating LLM-proposed text against Layer E ParadoxDetector.
///
/// Wire format: serde tagged enum with `kind` field, so
/// `Accept { ... }` → `{ "kind": "accept", "violations": [...], ... }`.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum ValidationOutcome {
    /// Proposed text introduces no new paradoxes and resolves all originals.
    Accept {
        /// Original violations still present (should be empty on full accept).
        violations: Vec<String>,
        /// Original paradox IDs still detected (should be empty on full accept).
        paradoxes: Vec<String>,
    },
    /// Proposed text introduces new paradoxes or fails to resolve originals.
    Reject {
        /// List of new violations introduced by the proposed text.
        violations: Vec<String>,
        /// Prompt to feed back to the LLM for regeneration.
        feedback_prompt: String,
    },
    /// Proposed text is unparseable or empty — ask the LLM to try again.
    Retry {
        /// Reason for the retry (e.g. "Empty text", "No SVO triplets found").
        reason: String,
    },
}

