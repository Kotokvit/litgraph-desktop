/// Generate a deterministic-enough unique ID for a hypothesis.
fn make_hypothesis_id() -> String {
    use std::sync::atomic::{AtomicU64, Ordering};
    static COUNTER: AtomicU64 = AtomicU64::new(0);
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    let ts = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos() as u64)
        .unwrap_or(0);
    format!("hg-{:016x}-{:04x}", ts, n & 0xffff)
}

/// Human-readable label for a [`ParadoxKind`].
fn paradox_kind_label(k: ParadoxKind) -> &'static str {
    match k {
        ParadoxKind::DeadSpeaking => "dead-speaking",
        ParadoxKind::SpatialTeleportation => "spatial-teleportation",
    }
}

/// Build a feedback prompt for the LLM when validation rejects the proposed text.
fn build_feedback_prompt(
    introduced: &[&Paradox],
    persisting: &[&Paradox],
) -> String {
    let mut prompt = String::from(
        "Your previous response did not resolve the paradox. Please regenerate the chapter section addressing these issues:\n\n",
    );
    if !introduced.is_empty() {
        prompt.push_str("NEW paradoxes introduced by your text:\n");
        for p in introduced {
            prompt.push_str(&format!(
                "- {} ({}): {}\n",
                paradox_kind_label(p.kind),
                p.character,
                p.explanation
            ));
        }
        prompt.push('\n');
    }
    if !persisting.is_empty() {
        prompt.push_str("ORIGINAL paradoxes that still persist:\n");
        for p in persisting {
            prompt.push_str(&format!(
                "- {} ({}): {}\n",
                paradox_kind_label(p.kind),
                p.character,
                p.explanation
            ));
        }
        prompt.push('\n');
    }
    prompt.push_str(
        "Rewrite the chapter section so that these paradoxes are explicitly resolved. \
         If the paradox is dead-speaking, ensure the character does not appear \
         alive after their death chapter. If the paradox is spatial-teleportation, \
         add a transit verb (поїхати, прибути, піти) or set the scene in the \
         same location as the previous chapter.",
    );
    prompt
}

/// The system prompt used for all Layer G LLM calls.
const SYSTEM_PROMPT: &str = "\
You are a literary reasoning assistant working with the POLER v7.5-LEM \
symbolic engine. Your task is to propose hypotheses that resolve temporal \
paradoxes in Ukrainian-language literary manuscripts, and to generate \
chapter text that implements those hypotheses.\n\n\
You must respond in strict JSON when asked for hypotheses, and in plain \
Ukrainian prose when asked for chapter text. Never include meta-commentary, \
markdown formatting, or explanations outside the requested format.\n\n\
The four canonical hypothesis kinds are:\n\
1. flashback — the character's appearance after death is a memory/flashback\n\
2. dreamSequence — the character's appearance is part of a dream or hallucination\n\
3. unrecordedResurrection — the character was not actually dead (magical/medical return)\n\
4. disguisedIdentity — the 'dead' character is an impostor or twin\n\n\
Always propose exactly one hypothesis of each kind (4 total) when asked.";

