//! Layer G — LLM Reasoning Bridge.
//!
//! Consumes paradoxes from Layer E's [`ParadoxDetector`], generates 4
//! canonical resolution hypotheses via an LLM, and validates the LLM's
//! proposed text against the deterministic Layer E ParadoxDetector
//! (no LLM call for validation — pure symbolic check).
//!
//! ## Architecture
//!
//! ```text
//!     ParadoxDetector (Layer E)
//!         ↓ Vec<Paradox>
//!     LlmBridge::generate_hypotheses(paradox, provider)
//!         ↓ Vec<Hypothesis>
//!     [User picks a hypothesis in PolerPanel UI]
//!         ↓ selected Hypothesis
//!     LlmBridge::generate_resolution_text(hypothesis, provider)
//!         ↓ String (proposed chapter text)
//!     LlmBridge::validate(proposed_text, original_paradoxes)
//!         ↓ ValidationOutcome (accept | reject | retry)
//!     [If reject → feed back to LLM with feedback_prompt]
//! ```
//!
//! ## Canonical hypothesis kinds
//!
//! Per `POLER_UA_LP_MASTER_ROADMAP_V8.md` §Layer G, every paradox must
//! produce exactly 4 hypotheses — one of each kind:
//!
//! - [`Flashback`](HypothesisKind::Flashback) — спогад про померлого персонажа
//! - [`DreamSequence`](HypothesisKind::DreamSequence) — сон або галюцинація
//! - [`UnrecordedResurrection`](HypothesisKind::UnrecordedResurrection) —
//!   сюжетне воскресіння (магія/медицина)
//! - [`DisguisedIdentity`](HypothesisKind::DisguisedIdentity) —
//!   самозванець / подвійник
//!
//! ## Determinism note
//!
//! `generate_hypotheses` and `generate_resolution_text` are non-deterministic
//! (they call an LLM). Tests must use a mock provider, never a real LLM.
//!
//! `validate` is fully deterministic — same input ⇒ same output. It re-runs
//! the Layer E `ParadoxDetector` on the proposed text and compares against
//! the original paradoxes.

