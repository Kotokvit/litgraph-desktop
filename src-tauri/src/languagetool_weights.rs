/// Одно лексическое правило из LanguageTool.
///
/// Поля:
/// - `rule_id` — идентификатор rulegroup в исходном XML (например,
///   `"PODARIT_PODAROK"`, `"PRYIMATY_VS_BRATY"`). Используется для
///   отладки и audit trail.
/// - `rule_name` — человекочитаемое название правила на языке оригинала.
/// - `category` — категория правила (LOGIC, GRAMMAR, STYLE, BARBARISM, ...).
/// - `rule_type` — классификация: tautology / paronym / barbarism /
///   collocation / logic / style / grammar / typo / other.
/// - `wrong_token_groups` — список групп токенов. Каждая группа = одна
///   позиция в pattern; содержит альтернативы (для regexp-токенов).
///   Для срабатывания правила все группы должны совпасть (по любой
///   альтернативе в каждой группе) с использованием stem-matching.
/// - `correct_suggestions` — список правильных вариантов (для замены).
/// - `example` — пример из XML (для документации/тестов).
#[derive(Debug, Clone)]
pub struct LexicalRule {
    pub rule_id: &'static str,
    pub rule_name: &'static str,
    pub category: &'static str,
    pub rule_type: &'static str,
    pub wrong_token_groups: &'static [&'static [&'static str]],
    pub correct_suggestions: &'static [&'static str],
    pub example: &'static str,
}

/// Проверяет, совпадает ли хотя бы одна альтернатива из группы
/// с подстрокой в тексте. Использует stem-matching для инфлектированных
/// форм: 'подарить' → совпадает с 'подарил', 'подарю', 'подаренный'.
///
/// Алгоритм:
/// 1. Точное совпадение подстроки.
/// 2. Prefix-matching: берём первые N символов (N = len-3, min 5) и ищем.
///    Это работает для русских глаголов с чередованием согласных
///    (возвращаться → возвращался, т→л) — prefix 'возвра' совпадает.
/// 3. Если альтернатива заканчивается на 'ся'/'сь' — отрезаем и пробуем.
fn token_group_matches(text_lower: &str, alternatives: &[&str]) -> bool {
    for alt in alternatives {
        let alt_lc = alt.to_lowercase();
        // 1. Точное совпадение подстроки
        if text_lower.contains(&alt_lc) {
            return true;
        }
        // 2. Prefix-matching (Unicode-safe по chars)
        let chars: Vec<char> = alt_lc.chars().collect();
        if chars.len() >= 6 {
            // Пробуем prefix длиной len-3 (минимум 5 символов)
            let prefix_len = std::cmp::max(5, chars.len() - 3);
            let prefix: String = chars[..prefix_len].iter().collect();
            if text_lower.contains(&prefix) {
                return true;
            }
        }
        // 3. Если альтернатива на '-ся'/'-сь' — отрезаем и ищем
        if alt_lc.ends_with("ся") || alt_lc.ends_with("сь") {
            let trimmed: String = chars[..chars.len() - 2].iter().collect();
            if trimmed.len() >= 4 && text_lower.contains(&trimmed) {
                return true;
            }
            // И ещё prefix от обрезанной формы
            let trimmed_chars: Vec<char> = trimmed.chars().collect();
            if trimmed_chars.len() >= 6 {
                let prefix_len = std::cmp::max(5, trimmed_chars.len() - 3);
                let prefix: String = trimmed_chars[..prefix_len].iter().collect();
                if text_lower.contains(&prefix) {
                    return true;
                }
            }
        }
    }
    false
}

/// Проверяет, сработало ли правило: ВСЕ группы токенов должны совпасть.
pub fn rule_matches(rule: &LexicalRule, text: &str) -> bool {
    let lc = text.to_lowercase();
    rule.wrong_token_groups
        .iter()
        .all(|group| token_group_matches(&lc, group))
}

