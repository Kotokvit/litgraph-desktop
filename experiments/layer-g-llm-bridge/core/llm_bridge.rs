/// Parse the LLM's JSON response into 4 [`Hypothesis`] structs.
///
/// The LLM is instructed to emit:
///
/// ```json
/// [
///   { "kind": "flashback", "summary": "...", "rationale": "...", "confidence": 0.8 },
///   { "kind": "dreamSequence", "summary": "...", "rationale": "...", "confidence": 0.6 },
///   { "kind": "unrecordedResurrection", "summary": "...", "rationale": "...", "confidence": 0.5 },
///   { "kind": "disguisedIdentity", "summary": "...", "rationale": "...", "confidence": 0.7 }
/// ]
/// ```
///
/// This function:
/// 1. Strips Markdown code fences if present (```json ... ```).
/// 2. Tries `serde_json::from_str`.
/// 3. Validates that all 4 `HypothesisKind` variants are present (one each).
/// 4. Generates a UUID-style id for each hypothesis.
pub fn parse_hypotheses(llm_response: &str, paradox_id: &str) -> Result<Vec<Hypothesis>, String> {
    // 1. Strip Markdown code fences if present.
    let json_str = strip_code_fences(llm_response).trim().to_string();

    // 2. Try to find the JSON array (in case the LLM added prose before/after).
    let json_str = extract_json_array(&json_str)?;

    // 3. Parse into intermediate structs.
    #[derive(Deserialize)]
    #[serde(rename_all = "camelCase")]
    struct RawHypothesis {
        kind: HypothesisKind,
        summary: String,
        rationale: String,
        confidence: f64,
    }

    let raws: Vec<RawHypothesis> = serde_json::from_str(&json_str).map_err(|e| {
        format!(
            "Failed to parse LLM response as JSON: {}. Response snippet: {}",
            e,
            &llm_response[..llm_response.len().min(200)]
        )
    })?;

    // 4. Validate all 4 canonical kinds are present.
    let mut seen_kinds: std::collections::HashSet<HypothesisKind> = std::collections::HashSet::new();
    for r in &raws {
        if !seen_kinds.insert(r.kind.clone()) {
            return Err(format!(
                "Duplicate hypothesis kind '{:?}' in LLM response",
                r.kind
            ));
        }
    }
    for kind in HypothesisKind::all() {
        if !seen_kinds.contains(kind) {
            return Err(format!(
                "Missing canonical hypothesis kind '{:?}' in LLM response",
                kind
            ));
        }
    }

    // 5. Generate UUID-style ids and assemble final Hypothesis structs.
    let hypotheses: Vec<Hypothesis> = raws
        .into_iter()
        .map(|r| Hypothesis {
            id: make_hypothesis_id(),
            paradox_id: paradox_id.to_string(),
            kind: r.kind,
            summary: r.summary,
            proposed_text: None,
            confidence: r.confidence.clamp(0.0, 1.0),
            rationale: r.rationale,
        })
        .collect();

    Ok(hypotheses)
}

/// Strip Markdown code fences (```json ... ``` or ``` ... ```).
fn strip_code_fences(s: &str) -> String {
    let trimmed = s.trim();
    if !trimmed.starts_with("```") {
        return s.to_string();
    }
    // Find the opening fence end (first newline after ```).
    let after_open = &trimmed[3..];
    let after_lang = if after_open.starts_with("json") {
        &after_open[4..]
    } else {
        after_open
    };
    // Find the closing fence.
    if let Some(close) = after_lang.rfind("```") {
        after_lang[..close].trim().to_string()
    } else {
        // No closing fence — just strip the opening.
        after_lang.trim().to_string()
    }
}

/// Extract the first JSON array `[...]` from a string that may have
/// prose before/after the array.
fn extract_json_array(s: &str) -> Result<String, String> {
    let start = s.find('[').ok_or_else(|| {
        format!(
            "No JSON array start '[' found in LLM response. Snippet: {}",
            &s[..s.len().min(200)]
        )
    })?;
    let end = s.rfind(']').ok_or_else(|| {
        format!(
            "No JSON array end ']' found in LLM response. Snippet: {}",
            &s[..s.len().min(200)]
        )
    })?;
    Ok(s[start..=end].to_string())
}

