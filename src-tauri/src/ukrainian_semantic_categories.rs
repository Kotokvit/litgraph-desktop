/// Повертає правильну форму для українського пароніма.
pub fn ukrainian_paronym_correct(word: &str) -> Option<&'static str> {
    let lc = word.trim().to_lowercase();
    if lc.is_empty() {
        return None;
    }
    UK_PARONYMS
        .iter()
        .find(|(correct, wrong)| *wrong == lc)
        .map(|(correct, _)| *correct)
}

