/// Проверяет, содержит ли текст русскую тавтологию.
/// Возвращает идентификатор правила или `None`.
/// Использует stem-matching для инфлектированных форм.
pub fn find_russian_tautology(text: &str) -> Option<&'static str> {
    let lc = text.to_lowercase();
    RUSSIAN_LT_RULES
        .iter()
        .filter(|rule| RUSSIAN_TAUTOLOGY_RULE_IDS.contains(&rule.rule_id))
        .find(|rule| rule.wrong_token_groups.iter().all(|g| token_group_matches(&lc, g)))
        .map(|rule| rule.rule_name)
}

/// Проверяет, является ли слово русским паронимом (часто путаемым).
/// Возвращает корректный вариант, если слово найдено в таблице
/// ошибочных форм.
pub fn russian_paronym_correction(word: &str) -> Option<&'static str> {
    let lc = word.trim().to_lowercase();
    RUSSIAN_PARONYM_PAIRS
        .iter()
        .find(|(_, wrong)| *wrong == lc)
        .map(|(correct, _)| *correct)
}

/// Проверяет, содержит ли текст неверную русскую коллокацию.
/// Возвращает корректный вариант или `None`.
pub fn russian_collocation_fix(text: &str) -> Option<&'static str> {
    let lc = text.to_lowercase();
    RUSSIAN_COLLOCATION_FIXES
        .iter()
        .find(|(wrong, _)| lc.contains(*wrong))
        .map(|(_, correct)| *correct)
}

/// Проверяет, содержит ли украинский текст варваризм.
/// Возвращает корректный вариант или `None`.
/// Использует stem-matching через [`rule_matches`].
pub fn ukrainian_barbarism_fix(text: &str) -> Option<&'static str> {
    find_ukrainian_lt_violation(text)
        .and_then(|rule| rule.correct_suggestions.first().copied())
}

/// Ищет первое сработавшее русское LT-правило в тексте.
/// Возвращает ссылку на `LexicalRule` или `None`.
pub fn find_russian_lt_violation(text: &str) -> Option<&'static LexicalRule> {
    RUSSIAN_LT_RULES
        .iter()
        .find(|rule| rule_matches(rule, text))
}

/// Ищет первое сработавшее украинское LT-правило в тексте.
pub fn find_ukrainian_lt_violation(text: &str) -> Option<&'static LexicalRule> {
    UKRAINIAN_LT_RULES
        .iter()
        .find(|rule| rule_matches(rule, text))
}

/// Возвращает количество русских LT-правил (для тестов/отладки).
pub fn russian_rules_count() -> usize {
    RUSSIAN_LT_RULES.len()
}

/// Возвращает количество украинских LT-правил (для тестов/отладки).
pub fn ukrainian_rules_count() -> usize {
    UKRAINIAN_LT_RULES.len()
}

