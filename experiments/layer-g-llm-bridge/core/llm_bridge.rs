/// The LLM Reasoning Bridge.
///
/// Holds a reference to the AI provider and exposes three methods:
/// - [`generate_hypotheses`](Self::generate_hypotheses)
/// - [`generate_resolution_text`](Self::generate_resolution_text)
/// - [`validate`](Self::validate)
///
/// The first two are non-deterministic (LLM calls). The third is fully
/// deterministic — it re-runs the Layer E ParadoxDetector on the proposed
/// text and compares against the original paradoxes.
pub struct LlmBridge {
    provider: AiProvider,
}

impl LlmBridge {
    pub fn new(provider: AiProvider) -> Self {
        Self { provider }
    }

    /// Generate 4 canonical hypotheses for a single paradox.
    ///
    /// Calls the LLM with a structured prompt (see
    /// [`build_paradox_resolution_prompt`](crate::ai::prompts::build_paradox_resolution_prompt)),
    /// then parses the JSON response into 4 [`Hypothesis`] structs — one of
    /// each [`HypothesisKind`].
    ///
    /// ## Errors
    /// Returns `Err(String)` if:
    /// - The LLM call fails (network error, auth error, etc.)
    /// - The response can't be parsed as JSON
    /// - The response doesn't contain all 4 canonical kinds
    pub async fn generate_hypotheses(&self, paradox: &Paradox) -> Result<Vec<Hypothesis>, String> {
        let prompt = crate::ai::prompts::build_paradox_resolution_prompt(paradox);
        let messages = vec![
            ChatMessage {
                role: "system".to_string(),
                content: SYSTEM_PROMPT.to_string(),
            },
            ChatMessage {
                role: "user".to_string(),
                content: prompt,
            },
        ];
        let response = chat(&self.provider, messages)
            .await
            .map_err(|e| format!("LLM call failed: {}", e))?;
        parse_hypotheses(&response, &paradox.id)
    }

    /// Generate full resolution text for a chosen hypothesis.
    ///
    /// Calls the LLM with the hypothesis kind + summary + rationale and asks
    /// for a 500-1500 word chapter section that resolves the paradox.
    ///
    /// Returns a new [`Hypothesis`] with `proposed_text` populated (all other
    /// fields copied from the input).
    pub async fn generate_resolution_text(
        &self,
        hypothesis: &Hypothesis,
    ) -> Result<Hypothesis, String> {
        let prompt = crate::ai::prompts::build_resolution_text_prompt(hypothesis);
        let messages = vec![
            ChatMessage {
                role: "system".to_string(),
                content: SYSTEM_PROMPT.to_string(),
            },
            ChatMessage {
                role: "user".to_string(),
                content: prompt,
            },
        ];
        let response = chat(&self.provider, messages)
            .await
            .map_err(|e| format!("LLM call failed: {}", e))?;
        Ok(Hypothesis {
            proposed_text: Some(response),
            ..hypothesis.clone()
        })
    }

    /// Validate LLM-proposed text against the deterministic Layer E
    /// ParadoxDetector (no LLM call here — pure symbolic check).
    ///
    /// ## Algorithm
    /// 1. Run `detect_chapters` (Layer A) on the proposed text to split it
    ///    into chapters. If no chapter headers are found, treat the whole
    ///    text as a single chapter.
    /// 2. For each chapter, run `detect_characters` (Layer B) and
    ///    `SvoParser::parse_text` (Layer C).
    /// 3. Run `ParadoxDetector::detect` on the resulting `ManuscriptAnalysis`.
    /// 4. Compare the new paradoxes against `original_paradoxes`:
    ///    - If the proposed text has zero paradoxes → `Accept`.
    ///    - If the proposed text has the same paradoxes as the original →
    ///      `Reject` with feedback asking the LLM to address them.
    ///    - If the proposed text has *new* paradoxes → `Reject` with
    ///      feedback listing the new violations.
    /// 5. If the proposed text is empty or unparseable → `Retry`.
    pub fn validate(
        &self,
        proposed_text: &str,
        original_paradoxes: &[Paradox],
    ) -> ValidationOutcome {
        if proposed_text.trim().is_empty() {
            return ValidationOutcome::Retry {
                reason: "Proposed text is empty.".to_string(),
            };
        }

        // Layer A: split into chapters. If no chapter headers are found,
        // treat the whole text as a single chapter (same fallback as
        // cmd_detect_paradoxes in src-tauri/src/commands/poler.rs).
        let (parsed_chapters, _prologue) = crate::parser::chapters::detect(proposed_text);
        let chapter_texts: Vec<&str> = if parsed_chapters.is_empty() {
            vec![proposed_text]
        } else {
            parsed_chapters.iter().map(|c| c.full_text.as_str()).collect()
        };

        // Layer B + C: per-chapter characters + SVO triplets.
        let parser = crate::linguistic::svo_parser::SvoParser::new();
        let characters_per_chapter: Vec<Vec<crate::parser::characters::ParsedCharacter>> =
            chapter_texts
                .iter()
                .map(|t| crate::parser::characters::detect(t))
                .collect();
        let triplets_per_chapter: Vec<Vec<crate::linguistic::svo_parser::SvoTriplet>> =
            chapter_texts
                .iter()
                .map(|t| parser.parse_text(t))
                .collect();

        // Layer E: run ParadoxDetector on the assembled manuscript.
        let manuscript = crate::reasoning::ManuscriptAnalysis {
            chapters: chapter_texts.into_iter().collect::<Vec<&str>>(),
            characters_per_chapter,
            triplets_per_chapter,
        };
        let mut detector = ParadoxDetector::new();
        let new_paradoxes = detector.detect(&manuscript);

        // Build sets of paradox signatures (character + kind) for comparison.
        let original_sigs: std::collections::HashSet<(String, ParadoxKind)> = original_paradoxes
            .iter()
            .map(|p| (p.character.to_lowercase(), p.kind))
            .collect();
        let _new_sigs: std::collections::HashSet<(String, ParadoxKind)> = new_paradoxes
            .iter()
            .map(|p| (p.character.to_lowercase(), p.kind))
            .collect();

        // Paradoxes that are NEW (introduced by the proposed text).
        let introduced: Vec<&Paradox> = new_paradoxes
            .iter()
            .filter(|p| !original_sigs.contains(&(p.character.to_lowercase(), p.kind)))
            .collect();
        // Original paradoxes that PERSIST (still detected in the proposed text).
        let persisting: Vec<&Paradox> = new_paradoxes
            .iter()
            .filter(|p| original_sigs.contains(&(p.character.to_lowercase(), p.kind)))
            .collect();

        if introduced.is_empty() && persisting.is_empty() {
            // No new paradoxes, no persisting originals → accept.
            ValidationOutcome::Accept {
                violations: vec![],
                paradoxes: vec![],
            }
        } else {
            // Reject — collect violations and build feedback prompt.
            let mut violations: Vec<String> = vec![];
            for p in &introduced {
                violations.push(format!(
                    "New {} paradox introduced for character '{}': {}",
                    paradox_kind_label(p.kind),
                    p.character,
                    p.explanation
                ));
            }
            for p in &persisting {
                violations.push(format!(
                    "Original {} paradox for character '{}' not resolved: {}",
                    paradox_kind_label(p.kind),
                    p.character,
                    p.explanation
                ));
            }
            let feedback_prompt = build_feedback_prompt(&introduced, &persisting);
            ValidationOutcome::Reject {
                violations,
                feedback_prompt,
            }
        }
    }
}

