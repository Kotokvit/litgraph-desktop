    fn test_parse_hypotheses_clamps_confidence() {
        let json = r#"[
            { "kind": "flashback", "summary": "A", "rationale": "B", "confidence": 1.5 },
            { "kind": "dreamSequence", "summary": "C", "rationale": "D", "confidence": -0.3 },
            { "kind": "unrecordedResurrection", "summary": "E", "rationale": "F", "confidence": 0.5 },
            { "kind": "disguisedIdentity", "summary": "G", "rationale": "H", "confidence": 0.7 }
        ]"#;
        let paradox = make_paradox("Петро", ParadoxKind::DeadSpeaking);
        let hyps = parse_hypotheses(json, &paradox.id).expect("must parse");
        // Confidence > 1.0 should be clamped to 1.0, < 0.0 to 0.0.
        let flashback = hyps.iter().find(|h| h.kind == HypothesisKind::Flashback).unwrap();
        assert_eq!(flashback.confidence, 1.0);
        let dream = hyps.iter().find(|h| h.kind == HypothesisKind::DreamSequence).unwrap();
        assert_eq!(dream.confidence, 0.0);
    }

